"""Phase 9.2: the four ragas metrics over the production retrieval path.

One question at a time: the top-:data:`~tests.eval.harness.TOP_K` items the *production*
:func:`numenews.vector.hybrid_search_news` returns become the retrieved contexts, the eval's
answerer writes an answer from them, and ragas scores the pair against the fixture reference:

| Metric | Answers | Gated at |
|---|---|---|
| `faithfulness` | is every claim in the answer supported by the contexts? | 0.7 |
| `context_precision` | do the useful contexts come first? | 0.6 |
| `context_recall` | do the contexts cover the reference? | reported only |
| `answer_relevancy` | does the answer address the question? | reported only |

The run writes `docs/eval_report.md` before it asserts anything, so a below-floor score is still
readable in the report that caused it. Without a configured endpoint the whole module skips: the
deterministic half of the eval lives in ``test_retrieval.py`` and needs no model.

The scores come from an LLM judge and move a little between runs and endpoints; the report records
which model produced them, and `docs/EVAL.md` says how to read that.
"""

from __future__ import annotations

import asyncio
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import UTC, datetime

import pytest

from numenews.config import Settings
from numenews.models import NewsItem
from numenews.vector import VectorStore

from . import judge
from .harness import (
    HIT_FLOOR,
    REPO_ROOT,
    TOP_K,
    EvalQuestion,
    contexts,
    hit,
    relevant_ids,
    retrieve,
)

#: Floors from roadmap 9.2; the two metrics without one are reported, not gated.
FLOORS = {"faithfulness": 0.7, "context_precision": 0.6}

#: Every metric the run reports, in the order the report shows them.
METRIC_NAMES = ("faithfulness", "context_precision", "context_recall", "answer_relevancy")

#: How many questions are scored at once. Each one is a handful of judge calls, so this bounds the
#: request rate without serialising a run that takes minutes either way.
MAX_CONCURRENCY = 4

#: Where the run leaves its report.
REPORT_PATH = REPO_ROOT / "docs" / "eval_report.md"


@dataclass(frozen=True)
class ScoredQuestion:
    """One question, its retrieval outcome and the four metric values."""

    question: EvalQuestion
    retrieved_hit: bool
    answer: str
    scores: dict[str, float]


async def _score_question(
    question: EvalQuestion,
    store: VectorStore,
    news: Mapping[str, NewsItem],
    llm: object,
    embeddings: object,
    gate: asyncio.Semaphore,
) -> ScoredQuestion:
    """Retrieve, answer and score one question."""
    async with gate:
        items = retrieve(store, question.question)
        retrieved = contexts(items)
        answer = await judge.generate_answer(llm, question.question, retrieved)
        assert answer, f"{question.id}: the endpoint answered nothing"
        scores = {
            "faithfulness": await judge.score_faithfulness(
                llm,
                question=question.question,
                response=answer,
                retrieved=retrieved,
            ),
            "context_precision": await judge.score_context_precision(
                llm,
                question=question.question,
                reference=question.reference,
                retrieved=retrieved,
            ),
            "context_recall": await judge.score_context_recall(
                llm,
                question=question.question,
                reference=question.reference,
                retrieved=retrieved,
            ),
            "answer_relevancy": await judge.score_answer_relevancy(
                llm,
                embeddings,
                question=question.question,
                response=answer,
            ),
        }
        return ScoredQuestion(
            question=question,
            retrieved_hit=hit(items, relevant_ids(question, news)),
            answer=answer,
            scores=scores,
        )


def _render_report(
    settings: Settings,
    scored: Sequence[ScoredQuestion],
    means: Mapping[str, float],
    hit_rate: float,
    corpus_size: int,
) -> str:
    """Return ``docs/eval_report.md``: what ran, what it scored and how to read it."""
    endpoint = (
        str(settings.openai_base_url)
        if settings.openai_base_url is not None
        else "the provider default"
    )
    generated = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# RAG evaluation report",
        "",
        f"> Generated by `make test-eval` on {generated} with `ragas`. Judge: "
        f"`{settings.llm_model}` at {endpoint}.",
        f"> Corpus: {corpus_size} fixture articles in `tests/eval/fixtures/news.jsonl`, "
        f"{len(scored)} questions in `questions.jsonl`, top-{TOP_K} contexts per question.",
        "> Retrieval and answer-relevancy vectors are the project's own local `fastembed` models.",
        "",
        "## Metrics",
        "",
        "| Metric | Score | Floor | Verdict |",
        "| --- | --- | --- | --- |",
    ]
    for name in METRIC_NAMES:
        floor = FLOORS.get(name)
        floor_cell = f"≥ {floor:.2f}" if floor is not None else "—"
        verdict = "reported" if floor is None else ("pass" if means[name] >= floor else "fail")
        lines.append(f"| {name} | {means[name]:.3f} | {floor_cell} | {verdict} |")
    lines += [
        "",
        f"Retrieval: hit@{TOP_K} = {hit_rate:.3f} "
        f"({sum(1 for item in scored if item.retrieved_hit)}/{len(scored)}), "
        f"floor {HIT_FLOOR:.2f}.",
        "",
        "## Per question",
        "",
        f"| Question | hit@{TOP_K} | {' | '.join(METRIC_NAMES)} |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for item in scored:
        cells = " | ".join(f"{item.scores[name]:.3f}" for name in METRIC_NAMES)
        lines.append(f"| {item.question.id} | {'yes' if item.retrieved_hit else 'no'} | {cells} |")
    lines += [
        "",
        "## How to read this",
        "",
        "- The judge is a language model, so the numbers move between runs and endpoints; the",
        "  floors in `tests/eval/test_rag.py` are deliberately below the reported scores rather",
        "  than tuned to the last run.",
        "- A single question can drop to 0 when the judge's statement check misreads an answer the",
        "  contexts plainly support; the run is gated on the mean for exactly that reason.",
        "- `faithfulness` and `context_precision` are the gates of phase 9; `context_recall` and",
        "  `answer_relevancy` are reported so a regression is visible before it is gated.",
        "- The full details — endpoint, dataset format, how to add fixtures — are in",
        "  `docs/EVAL.md`.",
        "",
    ]
    return "\n".join(lines)


@pytest.mark.eval
async def test_rag_quality(
    eval_settings: Settings,
    eval_store: VectorStore,
    eval_news: dict[str, NewsItem],
    eval_questions: list[EvalQuestion],
) -> None:
    """Score every fixture question with ragas and hold the run to the phase-9 floors."""
    if not judge.endpoint_configured(eval_settings):
        pytest.skip(
            "no LLM endpoint configured: set OPENAI_API_KEY or OPENAI_BASE_URL and rerun "
            "`make test-eval` (docs/EVAL.md)"
        )
    llm = judge.build_judge(eval_settings)
    embeddings = judge.build_ragas_embeddings()
    gate = asyncio.Semaphore(MAX_CONCURRENCY)
    scored = list(
        await asyncio.gather(
            *(
                _score_question(question, eval_store, eval_news, llm, embeddings, gate)
                for question in eval_questions
            )
        )
    )
    means = {name: sum(item.scores[name] for item in scored) / len(scored) for name in METRIC_NAMES}
    hit_rate = sum(1 for item in scored if item.retrieved_hit) / len(scored)
    REPORT_PATH.write_text(
        _render_report(eval_settings, scored, means, hit_rate, len(eval_news)),
        encoding="utf-8",
    )
    assert hit_rate >= HIT_FLOOR, f"hit@{TOP_K} is {hit_rate:.3f}"
    for name, floor in FLOORS.items():
        assert means[name] >= floor, f"{name} is {means[name]:.3f}, floor {floor:.2f}"
